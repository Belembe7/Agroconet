function normalizeProductName(name: string) {
  return displayName(name)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toLowerCase();
}

export function productImageAsset(
  productName: string,
): ProductImageAsset | null {
  return productImages[normalizeProductName(productName)] ?? null;
}
